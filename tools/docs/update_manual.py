@dataclasses.dataclass
class Commit:
    sha: str
    short: str
    subject: str
    files: list[str]

    @property
    def conventional(self) -> tuple[str, str | None, bool, str]:
        m = CONVENTIONAL_RE.match(self.subject)
        if not m:
            return "other", None, False, self.subject
        t = m.group("type").lower()
        if t in ("feature",):
            t = "feat"
        if t not in {g for g, _ in CHANGE_GROUPS}:
            t = "other"
        return t, m.group("scope"), bool(m.group("bang")), m.group("subject")


def git(ctx: Ctx, *args: str, check: bool = True) -> str | None:
    try:
        proc = subprocess.run(["git", "-C", str(ctx.root), *args], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None if check else proc.stdout
    return proc.stdout


def git_head(ctx: Ctx) -> str | None:
    out = git(ctx, "rev-parse", "HEAD")
    return out.strip() if out else None


def git_commit_exists(ctx: Ctx, sha: str | None) -> bool:
    return bool(sha) and git(ctx, "cat-file", "-e", f"{sha}^{{commit}}") is not None


def git_commits(ctx: Ctx, base: str | None, max_count: int) -> list[Commit] | None:
    """Commits in base..HEAD (newest first), with changed files. None if git is unavailable."""
    if git_head(ctx) is None:
        return None
    rng = f"{base}..HEAD" if base else "HEAD"
    out = git(ctx, "log", "--no-merges", f"--max-count={max_count}", "--format=%x1e%H%x1f%h%x1f%s", "--name-only", rng)
    if out is None:
        return None
    commits = []
    for chunk in out.split("\x1e"):
        if not chunk.strip():
            continue
        header, _, rest = chunk.partition("\n")
        parts = header.split("\x1f")
        if len(parts) < 3:
            continue
        files = [ln.strip() for ln in rest.split("\n") if ln.strip()]
        commits.append(Commit(parts[0], parts[1], parts[2].strip(), files))
    return commits


def docs_only(commit: Commit, ctx: Ctx) -> bool:
    """True when every file is under the manual / docs tooling (e.g. the bot's own commits)."""
    if not commit.files:
        return False
    manual = ctx.config["manual_dir"].rstrip("/") + "/**"
    pats = [manual, "tools/docs/**"]
    return all(any(glob_to_regex(p).match(f) for p in pats) for f in commit.files)


