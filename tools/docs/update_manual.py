def is_external(url: str) -> bool:
    return bool(re.match(r"^[a-zA-Z][a-zA-Z0-9+.\-]*:", url)) or url.startswith("//")


def image_refs(text: str) -> list[tuple[int, str]]:
    masked = mask_code(text)
    refs = [(line_of(masked, m.start()), m.group(2)) for m in IMG_MD_RE.finditer(masked)]
    refs += [(line_of(masked, m.start()), m.group(1)) for m in IMG_HTML_RE.finditer(masked)]
    return sorted(refs)


def local_links(text: str) -> list[tuple[int, str]]:
    masked = mask_code(text)
    res = []
    for m in LINK_MD_RE.finditer(masked):
        url = m.group(1)
        if is_external(url) or url.startswith("#"):
            continue
        res.append((line_of(masked, m.start()), url))
    return res


def resolve_ref(chapter_file: Path, url: str) -> Path:
    url = url.split("#", 1)[0].split("?", 1)[0]
    return (chapter_file.parent / urllib.request.url2pathname(url)).resolve()


def shot_file(ctx: Ctx, shot_id: str) -> Path:
    return ctx.img_dir / f"{shot_id}.png"


def image_rel(ctx: Ctx, chapter: str, shot_id: str) -> str:
    return posix_relpath(shot_file(ctx, shot_id), ctx.chapter_file(chapter).parent)


def available_images(ctx: Ctx) -> list[Path]:
    if not ctx.src_dir.exists():
        return []
    return sorted(p for p in ctx.src_dir.rglob("*") if p.is_file() and p.suffix.lower() in IMAGE_EXTS)


def load_placeholders(ctx: Ctx) -> set[str]:
    """Shot ids whose image is currently a fallback copy (not a real screenshot)."""
    text = read_text(ctx.img_dir / PLACEHOLDERS_FILE)
    if not text:
        return set()
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return set()
    digest = data.get("sha256")
    res = set()
    for sid in data.get("shots", []):
        p = shot_file(ctx, sid)
        if p.exists() and sha256_bytes(p.read_bytes()) == digest:
            res.add(sid)
    return res


