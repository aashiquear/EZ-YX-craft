#!/usr/bin/env python3
"""Keep the EZ-YX-craft user manual in sync with the app.

The feature registry (``docs/manual/registry.json``, exported by
``ezyx docs-registry``) is the single source of truth for user-facing features.
This tool turns it into an mdBook manual and keeps that manual current:

  check         validate markers, images, links and SUMMARY.md (CI gate)
  scaffold      deterministic: create missing chapters / SUMMARY entries / feature
                blocks, regenerate reference/features.md and changelog.md
  revise        LLM step: rewrite chapters affected by registry or source changes
  all           scaffold -> revise -> scaffold -> check
  placeholders  copy a fallback image over screenshots that failed to render
  plan          print what `revise` would do (same as `revise --dry-run`)

Feature documentation lives between markers that tooling can find:

    <!-- feature:pipeline.stock -->
    ...
    <!-- /feature:pipeline.stock -->

Everything outside markers is hand-written prose and is preserved.

Python >= 3.10, standard library only. The ``anthropic`` SDK is used when it is
installed; otherwise the Messages API is called with urllib.
"""

