def chapter_title(reg: Registry, chapter: str) -> str:
    for m in reg.modules:
        if norm_chapter(m["chapter"]) == chapter:
            return m["title"]
    feats = reg.features_in_chapter(chapter)
    if feats:
        return feats[0]["title"]
    return PurePosixPath(chapter).stem.replace("-", " ").replace("_", " ").title()


def render_feature_body(ctx: Ctx, reg: Registry, f: dict[str, Any], chapter: str, chapter_h1: str | None) -> str:
    lines: list[str] = []
    if (chapter_h1 or "").strip().lower() != f["title"].strip().lower():
        lines += [f"## {f['title']}", ""]
    lines += [" ".join(str(f.get("summary", "")).split()), ""]
    steps = [s for s in (f.get("how_to") or []) if str(s).strip()]
    if steps:
        lines += ["**Steps**", ""]
        lines += [f"{i}. {' '.join(str(s).split())}" for i, s in enumerate(steps, 1)]
        lines.append("")
    for shot in reg.feature_shots(f):
        caption = shot.get("caption") or f["title"]
        lines += [f"![{caption}]({image_rel(ctx, chapter, shot['id'])})", ""]
    if f.get("since"):
        lines += [f"*Available since version {f['since']}.*", ""]
    return "\n".join(lines).strip("\n")


def new_chapter_text(ctx: Ctx, reg: Registry, chapter: str) -> str:
    title = chapter_title(reg, chapter)
    parts = [f"# {title}", ""]
    for m in reg.modules:
        if norm_chapter(m["chapter"]) == chapter and m.get("summary"):
            parts += [" ".join(str(m["summary"]).split()), ""]
    for f in reg.features_in_chapter(chapter):
        parts += [render_block(f["id"], render_feature_body(ctx, reg, f, chapter, title)), ""]
    return normalize_text("\n".join(parts))


def add_missing_blocks(ctx: Ctx, reg: Registry, chapter: str, text: str) -> tuple[str, list[str]]:
    blocks, errs = parse_blocks(text)
    if errs:
        for line, e in errs:
            ctx.log.error(e, ctx.rel(ctx.chapter_file(chapter)), line)
        return text, []
    have = {b.id for b in blocks}
    missing = [f for f in reg.features_in_chapter(chapter) if f["id"] not in have]
    if not missing:
        return text, []
    h1 = first_h1(text)
    rendered = "\n\n".join(render_block(f["id"], render_feature_body(ctx, reg, f, chapter, h1)) for f in missing)
    if blocks:
        pos = max(b.end for b in blocks)
        new = text[:pos].rstrip("\n") + "\n\n" + rendered + "\n\n" + text[pos:].lstrip("\n")
    else:
        new = text.rstrip("\n") + "\n\n" + rendered + "\n"
    return normalize_text(new), [f["id"] for f in missing]


def summary_links(text: str) -> list[str]:
    return [norm_chapter(m.group(1).split("#", 1)[0]) for m in LINK_MD_RE.finditer(mask_code(text)) if not is_external(m.group(1))]


def default_summary() -> str:
    return "\n".join(
        [
            "# Summary",
            "",
            "[Introduction](introduction.md)",
            "",
            "# User guide",
            "",
            "- [Getting started](getting-started.md)",
            "",
            "# Modules",
            "",
            SUMMARY_BEGIN,
            SUMMARY_END,
            "",
            "# Reference",
            "",
            "- [Feature reference](reference/features.md)",
            "- [Changelog](changelog.md)",
            "",
        ]
    )


def render_summary_region(ctx: Ctx, reg: Registry, outside: set[str]) -> list[str]:
    lines: list[str] = []
    emitted: set[str] = set()
    for m in reg.modules:
        mch = norm_chapter(m["chapter"])
        indent = ""
        if mch not in outside and mch not in emitted:
            lines.append(f"- [{m['title']}]({mch})")
            emitted.add(mch)
            indent = "  "
        for f in reg.features:
            if f.get("module") != m["id"]:
                continue
            ch = reg.feature_chapter(f)
            if ch in outside or ch in emitted or ch == mch:
                continue
            title = first_h1(read_text(ctx.chapter_file(ch)) or "") or chapter_title(reg, ch)
            lines.append(f"{indent}- [{md_link_text(title)}]({ch})")
            emitted.add(ch)
    for ch in reg.chapters():  # features whose module is unknown
        if ch not in outside and ch not in emitted:
            lines.append(f"- [{md_link_text(chapter_title(reg, ch))}]({ch})")
            emitted.add(ch)
    for key, title in (("features", "Feature reference"), ("changelog", "Changelog")):
        ch = ctx.config["generated"][key]
        if ch not in outside and ch not in emitted:
            lines.append(f"- [{title}]({ch})")
            emitted.add(ch)
    return lines


def md_link_text(text: str) -> str:
    return text.replace("[", "\\[").replace("]", "\\]")


def update_summary(ctx: Ctx, reg: Registry) -> None:
    text = read_text(ctx.summary_path)
    if text is None:
        text = default_summary()
    b, e = SUMMARY_BEGIN_RE.search(text), SUMMARY_END_RE.search(text)
    if not b or not e or e.start() < b.end():
        text = text.rstrip("\n") + "\n\n" + SUMMARY_BEGIN + "\n" + SUMMARY_END + "\n"
        b, e = SUMMARY_BEGIN_RE.search(text), SUMMARY_END_RE.search(text)
    assert b and e
    outside = set(summary_links(text[: b.start()] + text[e.end() :]))
    region = render_summary_region(ctx, reg, outside)
    new = text[: b.start()] + SUMMARY_BEGIN + "\n" + "".join(ln + "\n" for ln in region) + SUMMARY_END + text[e.end() :]
    write_if_changed(ctx, ctx.summary_path, normalize_text(new), "SUMMARY entries")


def feature_anchor(text: str | None, fid: str) -> str:
    """Anchor of the first heading inside the feature block ('' when the block has none)."""
    if not text:
        return ""
    blocks, _ = parse_blocks(text)
    for b in blocks:
        if b.id == fid:
            hs = headings(b.body(text))
            return "#" + slugify(hs[0][1]) if hs and hs[0][0] > 1 else ""
    return ""


def render_features_reference(ctx: Ctx, reg: Registry) -> str:
    ref_ch = ctx.config["generated"]["features"]
    ref_dir = ctx.chapter_file(ref_ch).parent
    ver = f" {reg.app_version}" if reg.app_version else ""
    lines = [
        "# Feature reference",
        "",
        GENERATED_NOTE,
        "",
        f"Every user-facing feature of EZ-YX-craft{ver}, grouped by module. "
        "Select a feature to open its section of the manual.",
        "",
    ]
    for m in reg.modules:
        feats = [f for f in reg.features if f.get("module") == m["id"]]
        if not feats:
            continue
        lines += [f"## {m['title']}", ""]
        if m.get("summary"):
            lines += [" ".join(str(m["summary"]).split()), ""]
        lines += ["| Feature | What it does | Since |", "|---|---|---|"]
        for f in feats:
            ch = reg.feature_chapter(f)
            href = posix_relpath(ctx.chapter_file(ch), ref_dir) + feature_anchor(read_text(ctx.chapter_file(ch)), f["id"])
            lines.append(f"| [{md_cell(md_link_text(f['title']))}]({href}) | {md_cell(first_sentence(str(f.get('summary', ''))))} | {md_cell(f.get('since', '')) or '-'} |")
        lines.append("")
    return normalize_text("\n".join(lines))


def render_change_groups(commits: list[Commit], ignore_types: set[str]) -> list[str]:
    groups: dict[str, list[str]] = {}
    for c in commits:
        t, scope, bang, subject = c.conventional
        if t in ignore_types:
            continue
        item = f"- {'**' + scope + ':** ' if scope else ''}{subject.strip()}{' (breaking change)' if bang else ''} (`{c.short}`)"
        groups.setdefault(t, []).append(item)
    lines: list[str] = []
    for t, title in CHANGE_GROUPS:
        if groups.get(t):
            lines += [f"### {title}", ""] + groups[t] + [""]
    return lines


def changelog_commits(ctx: Ctx, base: str | None) -> list[Commit] | None:
    if base and not git_commit_exists(ctx, base):
        base = None
    commits = git_commits(ctx, base, int(ctx.config["changelog_max_commits"]))
    if commits is None:
        return None
    return [c for c in commits if not docs_only(c, ctx)]


def render_unreleased(ctx: Ctx, state: dict[str, Any] | None) -> str:
    base = (state or {}).get("commit")
    commits = changelog_commits(ctx, base)
    lines = ["## Since the last manual revision", ""]
    if commits is None:
        lines += ["_Git history is not available._"]
    else:
        body = render_change_groups(commits, set(ctx.config["changelog_ignore_types"]))
        lines += body if body else ["_No changes since the last manual revision._"]
    return "\n".join(lines).strip("\n")


def render_changelog(ctx: Ctx, state: dict[str, Any] | None, existing: str | None) -> str:
    unreleased = f"{CHANGELOG_OPEN}\n{render_unreleased(ctx, state)}\n{CHANGELOG_CLOSE}"
    if existing and CHANGELOG_OPEN in existing and CHANGELOG_CLOSE in existing:
        a = existing.index(CHANGELOG_OPEN)
        b = existing.index(CHANGELOG_CLOSE) + len(CHANGELOG_CLOSE)
        return normalize_text(existing[:a] + unreleased + existing[b:])
    head = [
        "# Changelog",
        "",
        "What changed in EZ-YX-craft between revisions of this manual. This page is generated from the "
        "project's git history (grouped by [Conventional Commits](https://www.conventionalcommits.org/) type); "
        "older revisions are kept below.",
        "",
        unreleased,
        "",
    ]
    return normalize_text("\n".join(head))


def freeze_changelog(ctx: Ctx, state: dict[str, Any] | None, reg: Registry, head: str | None) -> None:
    """Move the 'since last revision' entries into a dated, permanent section."""
    path = ctx.chapter_file(ctx.config["generated"]["changelog"])
    existing = read_text(path)
    base = (state or {}).get("commit")
    commits = changelog_commits(ctx, base)
    if not commits:
        return
    body = render_change_groups(commits, set(ctx.config["changelog_ignore_types"]))
    if not body:
        return
    today = _dt.date.today().isoformat()
    ver = f" — app {reg.app_version}" if reg.app_version else ""
    sha = f" (`{head[:8]}`)" if head else ""
    section = "\n".join([f"## Manual revision {today}{ver}{sha}", ""] + body).strip("\n")
    # The new revision starts at HEAD, so the "since the last revision" block becomes empty.
    text = render_changelog(ctx, {"commit": head} if head else state, existing)
    b = text.index(CHANGELOG_CLOSE) + len(CHANGELOG_CLOSE)
    text = text[:b] + "\n\n" + section + "\n\n" + text[b:].lstrip("\n")
    write_if_changed(ctx, path, normalize_text(text), "changelog revision")


def scaffold(ctx: Ctx) -> int:
    reg, errors = load_registry(ctx)
    for e in errors:
        ctx.log.error(e, ctx.rel(ctx.registry_path))
    if reg is None or errors:
        return 1
    state = load_state(ctx)
    for chapter in reg.chapters():
        path = ctx.chapter_file(chapter)
        text = read_text(path)
        if text is None:
            write_if_changed(ctx, path, new_chapter_text(ctx, reg, chapter), "new chapter")
            continue
        new, added = add_missing_blocks(ctx, reg, chapter, text)
        if added:
            write_if_changed(ctx, path, new, "added " + ", ".join(added))
    gen = ctx.config["generated"]
    write_if_changed(ctx, ctx.chapter_file(gen["features"]), render_features_reference(ctx, reg), "feature reference")
    cl_path = ctx.chapter_file(gen["changelog"])
    write_if_changed(ctx, cl_path, render_changelog(ctx, state, read_text(cl_path)), "changelog")
    update_summary(ctx, reg)
    return 1 if ctx.log.errors else 0


