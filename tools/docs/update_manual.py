def check(ctx: Ctx, strict: bool = False, strict_images: bool = False) -> int:
    log = ctx.log
    reg, errors = load_registry(ctx)
    for e in errors:
        log.error(e, ctx.rel(ctx.registry_path))
    if reg is None:
        return 1
    reg_ids = set(reg.feature_by_id)
    shot_ids = set(reg.shots)
    placeholders = load_placeholders(ctx)

    summary = read_text(ctx.summary_path)
    if summary is None:
        log.error("SUMMARY.md is missing (run `update_manual.py scaffold`)", ctx.rel(ctx.summary_path))
        summary = ""
    linked = summary_links(summary)
    for line, url in local_links(summary):
        if not resolve_ref(ctx.summary_path, url).exists():
            log.error(f"SUMMARY.md links to missing file {url!r}", ctx.rel(ctx.summary_path), line)
    for ch in reg.chapters() + [ctx.config["generated"]["features"], ctx.config["generated"]["changelog"]]:
        if ch not in linked:
            log.error(f"chapter {ch!r} is not listed in SUMMARY.md (run `update_manual.py scaffold`)", ctx.rel(ctx.summary_path))

    # Every registry feature has a block in its chapter.
    chapter_blocks: dict[str, set[str]] = {}
    md_files = sorted(p for p in ctx.src_dir.rglob("*.md")) if ctx.src_dir.exists() else []
    texts = {p: read_text(p) or "" for p in md_files}
    for p, text in texts.items():
        blocks, errs = parse_blocks(text)
        for line, e in errs:
            log.error(e, ctx.rel(p), line)
        rel_ch = p.relative_to(ctx.src_dir).as_posix()
        chapter_blocks[rel_ch] = {b.id for b in blocks}
        for b in blocks:
            if b.id not in reg_ids:
                log.warning(f"stale feature block {b.id!r}: the feature is no longer in the registry (remove it or run `revise`)", ctx.rel(p), line_of(text, b.start))
            elif reg.feature_chapter(reg.feature_by_id[b.id]) != rel_ch:
                log.warning(f"feature block {b.id!r} is outside its registry chapter {reg.feature_chapter(reg.feature_by_id[b.id])!r}", ctx.rel(p), line_of(text, b.start))
    for f in reg.features:
        ch = reg.feature_chapter(f)
        if not ctx.chapter_file(ch).exists():
            log.error(f"chapter {ch!r} for feature {f['id']!r} does not exist (run `update_manual.py scaffold`)", ctx.rel(ctx.chapter_file(ch)))
        elif f["id"] not in chapter_blocks.get(ch, set()):
            log.error(f"feature {f['id']!r} has no `{open_marker(f['id'])}` block (run `update_manual.py scaffold`)", ctx.rel(ctx.chapter_file(ch)))
        for sid in f.get("shots", []) or []:
            if sid in placeholders:
                log.warning(f"screenshot {sid!r} is a placeholder image (GUI screenshot rendering failed)", ctx.rel(shot_file(ctx, sid)))

    # Images and local links.
    for p, text in texts.items():
        for line, url in image_refs(text):
            if is_external(url):
                log.error(f"external image {url!r}: images must live in the manual (src/img)", ctx.rel(p), line)
                continue
            target = resolve_ref(p, url)
            try:
                target.relative_to(ctx.src_dir)
            except ValueError:
                log.error(f"image {url!r} points outside the manual source directory", ctx.rel(p), line)
                continue
            if target.exists():
                continue
            stem_is_shot = target.parent == ctx.img_dir.resolve() and target.suffix == ".png" and target.stem in shot_ids
            if stem_is_shot and not strict_images:
                log.warning(f"screenshot {url!r} has not been rendered yet (tools/docs/render_shots.sh)", ctx.rel(p), line)
            else:
                log.error(f"image {url!r} does not exist", ctx.rel(p), line)
        for line, url in local_links(text):
            if p == ctx.summary_path:
                continue
            if not resolve_ref(p, url).exists():
                log.error(f"link to missing file {url!r}", ctx.rel(p), line)

    # Orphans: chapters on disk that the book never shows.
    linked_set = set(linked)
    for p in md_files:
        rel_ch = p.relative_to(ctx.src_dir).as_posix()
        if rel_ch != "SUMMARY.md" and rel_ch not in linked_set:
            log.warning("chapter is not listed in SUMMARY.md, so mdBook will not show it", ctx.rel(p))

    if strict and log.warnings:
        for w in list(log.warnings):
            log.errors.append("(strict) " + w)
    log.info(f"check: {len(log.errors)} error(s), {len(log.warnings)} warning(s)")
    return 1 if log.errors else 0


