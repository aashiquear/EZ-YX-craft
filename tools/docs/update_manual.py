@dataclasses.dataclass
class Registry:
    data: dict[str, Any]
    app_version: str
    modules: list[dict[str, Any]]
    features: list[dict[str, Any]]
    shots: dict[str, dict[str, Any]]

    @property
    def module_by_id(self) -> dict[str, dict[str, Any]]:
        return {m["id"]: m for m in self.modules}

    @property
    def feature_by_id(self) -> dict[str, dict[str, Any]]:
        return {f["id"]: f for f in self.features}

    def feature_chapter(self, f: dict[str, Any]) -> str:
        if f.get("chapter"):
            return norm_chapter(f["chapter"])
        mod = self.module_by_id.get(f.get("module", ""))
        return norm_chapter(mod["chapter"]) if mod else ""

    def module_chapter(self, module_id: str) -> str | None:
        mod = self.module_by_id.get(module_id)
        return norm_chapter(mod["chapter"]) if mod and mod.get("chapter") else None

    def chapters(self) -> list[str]:
        """All chapters in registry order: each module chapter followed by its feature chapters."""
        seen: list[str] = []
        for m in self.modules:
            for ch in [norm_chapter(m["chapter"])] + [self.feature_chapter(f) for f in self.features if f.get("module") == m["id"]]:
                if ch and ch not in seen:
                    seen.append(ch)
        for f in self.features:  # features with unknown module still get a chapter
            ch = self.feature_chapter(f)
            if ch and ch not in seen:
                seen.append(ch)
        return seen

    def features_in_chapter(self, chapter: str) -> list[dict[str, Any]]:
        return [f for f in self.features if self.feature_chapter(f) == chapter]

    def modules_of_chapter(self, chapter: str) -> list[str]:
        mods = [m["id"] for m in self.modules if norm_chapter(m["chapter"]) == chapter]
        for f in self.features_in_chapter(chapter):
            if f.get("module") and f["module"] not in mods:
                mods.append(f["module"])
        return mods

    def feature_shots(self, f: dict[str, Any]) -> list[dict[str, Any]]:
        res = []
        for sid in f.get("shots", []) or []:
            shot = self.shots.get(sid)
            res.append(shot if shot else {"id": sid})
        return res

    def feature_hash(self, f: dict[str, Any]) -> str:
        payload = {"feature": f, "shots": self.feature_shots(f)}
        return sha256_bytes(canonical_json(payload).encode("utf-8"))[:16]

    def registry_hash(self) -> str:
        return sha256_bytes(canonical_json(self.data).encode("utf-8"))[:16]


def norm_chapter(ch: str) -> str:
    ch = (ch or "").replace("\\", "/").strip()
    while ch.startswith("./"):
        ch = ch[2:]
    return ch


def parse_registry(data: dict[str, Any]) -> tuple[Registry, list[str]]:
    errors: list[str] = []
    if not isinstance(data, dict):
        return Registry({}, "", [], [], {}), ["registry root must be a JSON object"]
    modules = data.get("modules") or []
    features = data.get("features") or []
    shots_list = data.get("shots") or []
    shots: dict[str, dict[str, Any]] = {}
    for s in shots_list:
        if not isinstance(s, dict) or not s.get("id"):
            errors.append(f"shot entry without id: {s!r}")
            continue
        if s["id"] in shots:
            errors.append(f"duplicate shot id {s['id']!r}")
        if not re.fullmatch(r"[A-Za-z0-9_.\-]+", s["id"]):
            errors.append(f"shot id {s['id']!r} must be a plain file stem (letters, digits, _ . -)")
        shots[s["id"]] = s
    mod_ids: set[str] = set()
    for m in modules:
        for key in ("id", "title", "chapter"):
            if not isinstance(m, dict) or not m.get(key):
                errors.append(f"module {m!r} is missing {key!r}")
        if isinstance(m, dict) and m.get("id"):
            if m["id"] in mod_ids:
                errors.append(f"duplicate module id {m['id']!r}")
            mod_ids.add(m["id"])
            if m.get("chapter"):
                errors.extend(chapter_path_errors(m["chapter"], f"module {m['id']}"))
    feat_ids: set[str] = set()
    for f in features:
        if not isinstance(f, dict):
            errors.append(f"feature entry is not an object: {f!r}")
            continue
        for key in ("id", "module", "title", "summary"):
            if not f.get(key):
                errors.append(f"feature {f.get('id', f)!r} is missing {key!r}")
        fid = f.get("id")
        if fid:
            if not re.fullmatch(FEATURE_ID, fid):
                errors.append(f"feature id {fid!r} has characters not allowed in markers")
            if fid in feat_ids:
                errors.append(f"duplicate feature id {fid!r}")
            feat_ids.add(fid)
        if f.get("module") and f["module"] not in mod_ids:
            errors.append(f"feature {fid!r} references unknown module {f['module']!r}")
        if f.get("chapter"):
            errors.extend(chapter_path_errors(f["chapter"], f"feature {fid}"))
        if not isinstance(f.get("how_to", []), list):
            errors.append(f"feature {fid!r}: how_to must be a list of strings")
        for sid in f.get("shots", []) or []:
            if sid not in shots:
                errors.append(f"feature {fid!r} references unknown shot {sid!r}")
    reg = Registry(
        data=data,
        app_version=str(data.get("app_version", "")),
        modules=[m for m in modules if isinstance(m, dict) and m.get("id") and m.get("chapter")],
        features=[f for f in features if isinstance(f, dict) and f.get("id")],
        shots=shots,
    )
    return reg, errors


def chapter_path_errors(ch: str, who: str) -> list[str]:
    c = norm_chapter(ch)
    errs = []
    if c.startswith("/") or re.match(r"^[A-Za-z]:", c):
        errs.append(f"{who}: chapter {ch!r} must be relative to the manual src/ directory")
    if ".." in PurePosixPath(c).parts:
        errs.append(f"{who}: chapter {ch!r} must not contain '..'")
    if not c.endswith(".md"):
        errs.append(f"{who}: chapter {ch!r} must be a .md file")
    if c == "SUMMARY.md":
        errs.append(f"{who}: chapter cannot be SUMMARY.md")
    return errs


def load_registry(ctx: Ctx) -> tuple[Registry | None, list[str]]:
    text = read_text(ctx.registry_path)
    if text is None:
        return None, [f"registry not found: {ctx.rel(ctx.registry_path)} (export it with `ezyx docs-registry -o {ctx.config['registry']}`)"]
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        return None, [f"registry is not valid JSON: {e}"]
    return parse_registry(data)


