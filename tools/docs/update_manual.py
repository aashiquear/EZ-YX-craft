@dataclasses.dataclass
class Block:
    id: str
    start: int  # offset of the opening marker
    body_start: int  # offset just after the opening marker
    body_end: int  # offset of the closing marker
    end: int  # offset just after the closing marker

    def body(self, text: str) -> str:
        return text[self.body_start : self.body_end]


def parse_blocks(text: str) -> tuple[list[Block], list[tuple[int, str]]]:
    """Parse feature marker blocks. Returns (blocks, [(line, error)])."""
    blocks: list[Block] = []
    errors: list[tuple[int, str]] = []
    open_m: re.Match[str] | None = None
    seen: set[str] = set()
    for m in MARKER_RE.finditer(text):
        closing, fid = m.group(1) == "/", m.group(2)
        if not closing:
            if open_m is not None:
                errors.append((line_of(text, m.start()), f"feature block {fid!r} opened inside unclosed block {open_m.group(2)!r}"))
                continue
            open_m = m
        else:
            if open_m is None:
                errors.append((line_of(text, m.start()), f"closing marker for {fid!r} without an opening marker"))
                continue
            if open_m.group(2) != fid:
                errors.append((line_of(text, m.start()), f"closing marker {fid!r} does not match open block {open_m.group(2)!r}"))
                open_m = None
                continue
            if fid in seen:
                errors.append((line_of(text, open_m.start()), f"duplicate feature block {fid!r}"))
            seen.add(fid)
            blocks.append(Block(fid, open_m.start(), open_m.end(), m.start(), m.end()))
            open_m = None
    if open_m is not None:
        errors.append((line_of(text, open_m.start()), f"feature block {open_m.group(2)!r} is never closed"))
    return blocks, errors


def open_marker(fid: str) -> str:
    return f"<!-- feature:{fid} -->"


def close_marker(fid: str) -> str:
    return f"<!-- /feature:{fid} -->"


def render_block(fid: str, body: str) -> str:
    return f"{open_marker(fid)}\n{body.strip(chr(10))}\n{close_marker(fid)}"


def replace_block_body(text: str, fid: str, new_body: str) -> str:
    blocks, errs = parse_blocks(text)
    if errs:
        raise ValueError("; ".join(e for _, e in errs))
    for b in blocks:
        if b.id == fid:
            return text[: b.start] + render_block(fid, new_body) + text[b.end :]
    raise KeyError(fid)


def outside_blocks(text: str, blocks: list[Block]) -> str:
    parts, pos = [], 0
    for b in sorted(blocks, key=lambda b: b.start):
        parts.append(text[pos : b.start])
        pos = b.end
    parts.append(text[pos:])
    return "".join(parts)


