# Glob matching / path -> module mapping
# --------------------------------------------------------------------------------------


_GLOB_CACHE: dict[str, re.Pattern[str]] = {}


def glob_to_regex(pattern: str) -> re.Pattern[str]:
    """Translate a path glob (`**` spans directories, `*` and `?` stay in a segment)."""
    if pattern in _GLOB_CACHE:
        return _GLOB_CACHE[pattern]
    i, n, out = 0, len(pattern), []
    while i < n:
        c = pattern[i]
        if c == "*":
            if i + 1 < n and pattern[i + 1] == "*":
                i += 2
                if i < n and pattern[i] == "/":
                    i += 1
                    out.append(r"(?:.*/)?")
                else:
                    out.append(r".*")
                continue
            out.append(r"[^/]*")
        elif c == "?":
            out.append(r"[^/]")
        elif c == "[":
            j = pattern.find("]", i + 1)
            if j == -1:
                out.append(re.escape(c))
            else:
                out.append("[" + pattern[i + 1 : j].replace("\\", "\\\\") + "]")
                i = j
        else:
            out.append(re.escape(c))
        i += 1
    rx = re.compile("^" + "".join(out) + "$")
    _GLOB_CACHE[pattern] = rx
    return rx


def module_for_path(path: str, rules: list[dict[str, Any]]) -> str | None:
    """First matching rule wins. Returns the module id, or None (ignored / unmapped)."""
    path = path.replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    for rule in rules:
        if glob_to_regex(rule["glob"]).match(path):
            return rule.get("module")
    return None


def modules_for_paths(paths: Iterable[str], rules: list[dict[str, Any]]) -> dict[str, list[str]]:
    """module id -> list of paths that mapped to it."""
    res: dict[str, list[str]] = {}
    for p in paths:
        m = module_for_path(p, rules)
        if m:
            res.setdefault(m, []).append(p)
    return res


