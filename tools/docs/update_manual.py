class Log:
    """Collects errors and warnings; prints GitHub annotations inside Actions."""

    def __init__(self, quiet: bool = False) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.quiet = quiet
        self.gha = os.environ.get("GITHUB_ACTIONS") == "true"

    def info(self, msg: str) -> None:
        if not self.quiet:
            print(msg)

    def _emit(self, kind: str, msg: str, file: str | None, line: int | None) -> None:
        if self.quiet:
            return
        if self.gha:
            loc = ""
            if file:
                loc = f" file={file}" + (f",line={line}" if line else "")
            print(f"::{kind}{loc}::{msg}")
        else:
            where = f"{file}:{line}: " if file and line else (f"{file}: " if file else "")
            print(f"{kind.upper()}: {where}{msg}", file=sys.stderr)

    def error(self, msg: str, file: str | None = None, line: int | None = None) -> None:
        self.errors.append(msg if not file else f"{file}: {msg}")
        self._emit("error", msg, file, line)

    def warning(self, msg: str, file: str | None = None, line: int | None = None) -> None:
        self.warnings.append(msg if not file else f"{file}: {msg}")
        self._emit("warning", msg, file, line)


