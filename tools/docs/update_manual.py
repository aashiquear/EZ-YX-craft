def placeholders(ctx: Ctx, fallback: Path) -> int:
    reg, errors = load_registry(ctx)
    for e in errors:
        ctx.log.error(e, ctx.rel(ctx.registry_path))
    if reg is None:
        return 1
    if not fallback.exists():
        ctx.log.error(f"fallback image {fallback} does not exist")
        return 1
    data = fallback.read_bytes()
    digest = sha256_bytes(data)
    current = load_placeholders(ctx)  # still-unreplaced placeholders from earlier runs
    made = set()
    for sid in sorted(reg.shots):
        p = shot_file(ctx, sid)
        if p.exists() and sid not in current:
            continue
        if not ctx.dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(fallback, p)
        made.add(sid)
        ctx.log.info(f"placeholder {ctx.rel(p)} <- {fallback.name}")
    meta = ctx.img_dir / PLACEHOLDERS_FILE
    if made:
        write_if_changed(ctx, meta, json.dumps({"fallback": fallback.name, "sha256": digest, "shots": sorted(made)}, indent=2) + "\n")
    elif meta.exists() and not ctx.dry_run:
        meta.unlink()
    ctx.log.info(f"placeholders: {len(made)} screenshot(s) use the fallback image")
    return 0


