def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def normalize_text(text: str) -> str:
    """Unix newlines, no trailing whitespace on lines, exactly one trailing newline."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [ln.rstrip() for ln in text.split("\n")]
    out = "\n".join(lines).strip("\n")
    out = re.sub(r"\n{3,}", "\n\n", out)
    return out + "\n"


def read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def write_if_changed(ctx: Ctx, path: Path, text: str, what: str = "") -> bool:
    old = read_text(path)
    if old == text:
        return False
    verb = "create" if old is None else "update"
    if ctx.dry_run:
        ctx.log.info(f"[dry-run] would {verb} {ctx.rel(path)}{' (' + what + ')' if what else ''}")
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    ctx.log.info(f"{verb}d {ctx.rel(path)}{' (' + what + ')' if what else ''}")
    return True


def posix_relpath(target: Path, start_dir: Path) -> str:
    return PurePosixPath(os.path.relpath(target, start_dir).replace(os.sep, "/")).as_posix()


def slugify(title: str) -> str:
    """mdBook-compatible heading id (lowercase, alnum/-/_ kept, whitespace -> '-')."""
    title = re.sub(r"<[^>]+>", "", title)
    out = []
    for ch in title.strip().lower():
        if ch.isalnum() or ch in "-_":
            out.append(ch)
        elif ch.isspace():
            out.append("-")
    return "".join(out)


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    m = re.match(r"^(.+?[.!?])(\s|$)", text)
    return m.group(1) if m else text


def md_cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def mask_code(text: str) -> str:
    """Blank out fenced code blocks and inline code spans, keeping offsets/line numbers."""
    out_lines = []
    fence: str | None = None
    for line in text.split("\n"):
        stripped = line.lstrip()
        m = re.match(r"^(`{3,}|~{3,})", stripped)
        if fence is None and m:
            fence = m.group(1)[0] * len(m.group(1))
            out_lines.append(" " * len(line))
            continue
        if fence is not None:
            if stripped.startswith(fence) and stripped.strip(fence[0]).strip() == "":
                fence = None
            out_lines.append(" " * len(line))
            continue
        out_lines.append(re.sub(r"`[^`\n]*`", lambda mm: " " * len(mm.group(0)), line))
    return "\n".join(out_lines)


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def first_h1(text: str) -> str | None:
    for line in mask_code(text).split("\n"):
        m = H1_RE.match(line)
        if m:
            return m.group(1).strip()
    return None


def headings(text: str) -> list[tuple[int, str]]:
    res = []
    for line in mask_code(text).split("\n"):
        m = HEADING_RE.match(line)
        if m:
            res.append((len(m.group(1)), m.group(2).strip()))
    return res


