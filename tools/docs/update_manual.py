@dataclasses.dataclass
class ChapterPlan:
    chapter: str
    reasons: list[str]
    feature_ids: list[str]
    new_ids: list[str]
    changed_ids: list[str]
    removed_ids: list[str]
    base_commit: str | None
    module_commits: dict[str, list[Commit]]
    module_files: dict[str, list[str]]


def plan_revisions(ctx: Ctx, reg: Registry, state: dict[str, Any] | None) -> list[ChapterPlan]:
    rules = ctx.config["path_modules"]
    ignore_types = set(ctx.config["ignore_commit_types"])
    st_feats: dict[str, Any] = (state or {}).get("features", {})
    st_chapters: dict[str, Any] = (state or {}).get("chapters", {})
    commit_cache: dict[str | None, list[Commit] | None] = {}

    def commits_since(base: str | None) -> list[Commit] | None:
        if base not in commit_cache:
            commit_cache[base] = git_commits(ctx, base, 1000) if base and git_commit_exists(ctx, base) else None
        return commit_cache[base]

    plans = []
    for chapter in reg.chapters():
        feats = reg.features_in_chapter(chapter)
        ids = [f["id"] for f in feats]
        reasons: list[str] = []
        text = read_text(ctx.chapter_file(chapter)) or ""
        blocks, _ = parse_blocks(text)
        new_ids = [i for i in ids if i not in st_feats]
        changed_ids = [f["id"] for f in feats if f["id"] in st_feats and st_feats[f["id"]].get("hash") != reg.feature_hash(f)]
        removed = {fid for fid, v in st_feats.items() if v.get("chapter") == chapter and fid not in reg.feature_by_id}
        removed |= {b.id for b in blocks if b.id not in reg.feature_by_id}
        removed_ids = sorted(removed)
        if state is None:
            reasons.append("first revision (no .manual-state.json yet)")
        else:
            if new_ids:
                reasons.append("new feature(s): " + ", ".join(new_ids))
            if changed_ids:
                reasons.append("registry entry changed: " + ", ".join(changed_ids))
        if removed_ids:
            reasons.append("feature(s) removed from the registry: " + ", ".join(removed_ids))
        base = (st_chapters.get(chapter) or {}).get("commit") or (state or {}).get("commit")
        module_commits: dict[str, list[Commit]] = {}
        module_files: dict[str, list[str]] = {}
        commits = commits_since(base)
        if base and commits is None and state is not None:
            ctx.log.warning(f"{chapter}: recorded revision {base[:10]} is not in the git history; source changes are not considered")
        mods = set(reg.modules_of_chapter(chapter))
        for c in commits or []:
            if c.conventional[0] in ignore_types:
                continue
            for m, files in modules_for_paths(c.files, rules).items():
                if m in mods:
                    module_commits.setdefault(m, []).append(c)
                    for fp in files:
                        if fp not in module_files.setdefault(m, []):
                            module_files[m].append(fp)
        if module_commits and state is not None:
            reasons.append("source changes: " + ", ".join(f"{m} ({len(cs)} commit(s))" for m, cs in sorted(module_commits.items())))
        if reasons:
            plans.append(ChapterPlan(chapter, reasons, ids, new_ids, changed_ids, removed_ids, base, module_commits, module_files))
    return plans


def module_diff(ctx: Ctx, base: str | None, files: list[str], limit: int) -> str:
    if not base or not files:
        return ""
    files = files[:200]
    stat = git(ctx, "diff", "--stat=120", f"{base}..HEAD", "--", *files) or ""
    diff = git(ctx, "diff", "-U2", "--no-color", f"{base}..HEAD", "--", *files) or ""
    out = stat.strip() + "\n\n" + diff
    if len(out) > limit:
        out = out[:limit] + f"\n... [diff truncated, {len(out) - limit} more characters]\n"
    return out


SYSTEM_PROMPT = """You are the technical writer for the EZ-YX-craft user manual. EZ-YX-craft is an open-source desktop \
application for CNC wood and metal carving (design, toolpaths, G-code, material-removal preview, machine control, \
and an AI assistant). The manual is an mdBook; you revise one chapter at a time when the app changes.

You receive: the current chapter, the feature-registry entries that belong to it (the registry is the authoritative \
description of every user-facing feature, written by the developers), recent commits and a condensed diff for the \
modules involved, and the list of image files you may reference.

Rules:
1. Return the COMPLETE revised chapter between <revised_chapter> and </revised_chapter>. Nothing else is read.
   If the chapter is already accurate and complete, reply with exactly <unchanged/> instead.
2. Feature documentation lives between marker comments such as `<!-- feature:pipeline.stock -->` and \
`<!-- /feature:pipeline.stock -->`. Keep a marker pair, each marker on its own line and written exactly as given, \
for EVERY feature listed under "Features in this chapter". Put everything about a feature inside its markers. \
Do not invent markers for features that are not listed. Delete the marker blocks of features listed as removed, \
together with any other mention of them.
3. Text outside the markers was written by maintainers. Keep it verbatim unless the changes make it wrong; then \
correct it with the smallest edit that makes it right. Keep the chapter's `# ` title unless it is now wrong.
4. Only reference images from the "Available images" list, using exactly the relative path shown. Use each \
feature's screenshots where they help the reader. Never link external images.
5. Base every statement on the registry entries, commit messages and diff. Do not invent buttons, menu names, \
shortcuts, defaults or numbers. When the source is ambiguous, describe the behaviour at the level of detail the \
registry gives rather than guessing.
6. Follow the style guide below. Keep Markdown valid for mdBook (CommonMark tables, fenced code, relative links).
"""


def build_system_blocks(ctx: Ctx, reg: Registry) -> list[dict[str, Any]]:
    style = read_text(ctx.path("style_guide")) or "(style guide missing)"
    summary = read_text(ctx.summary_path) or ""
    reference = "\n\n".join(
        [
            SYSTEM_PROMPT,
            "# Style guide\n\n" + style.strip(),
            "# Manual table of contents (SUMMARY.md)\n\n" + summary.strip(),
            "# Complete feature registry (for context and cross-links)\n\n```json\n" + json.dumps(reg.data, indent=1, sort_keys=True) + "\n```",
        ]
    )
    # Stable for the whole run, so every chapter after the first reads it from the prompt cache.
    return [{"type": "text", "text": reference, "cache_control": {"type": "ephemeral"}}]


def build_user_prompt(ctx: Ctx, reg: Registry, plan: ChapterPlan, state: dict[str, Any] | None) -> str:
    text = read_text(ctx.chapter_file(plan.chapter)) or ""
    placeholders_set = load_placeholders(ctx)
    st_feats = (state or {}).get("features", {})
    parts = [f"# Chapter to revise: `{plan.chapter}`", "", "Why it needs revision:"]
    parts += [f"- {r}" for r in plan.reasons]
    parts += ["", "## Features in this chapter (each needs its marker block)", ""]
    for fid in plan.feature_ids:
        f = reg.feature_by_id[fid]
        status = "NEW" if fid in plan.new_ids else ("CHANGED" if fid in plan.changed_ids else "unchanged")
        entry = dict(f)
        entry["_screenshots"] = [
            {
                "id": s["id"],
                "caption": s.get("caption"),
                "path": image_rel(ctx, plan.chapter, s["id"]),
                "rendered": shot_file(ctx, s["id"]).exists(),
                "placeholder": s["id"] in placeholders_set,
            }
            for s in reg.feature_shots(f)
        ]
        parts += [f"### `{fid}` — {status}", "", f"Markers: `{open_marker(fid)}` … `{close_marker(fid)}`", "", "```json", json.dumps(entry, indent=1, ensure_ascii=False), "```", ""]
        prev = (st_feats.get(fid) or {}).get("entry")
        if status == "CHANGED" and prev:
            parts += ["Previous registry entry (what the chapter was written from):", "", "```json", json.dumps(prev, indent=1, ensure_ascii=False), "```", ""]
    if plan.removed_ids:
        parts += ["## Removed features (delete their blocks and mentions)", ""] + [f"- `{i}`" for i in plan.removed_ids] + [""]
    limit = int(ctx.config["diff_max_chars"])
    max_log = int(ctx.config["log_max_commits"])
    for m, commits in sorted(plan.module_commits.items()):
        parts += [f"## Source changes in module `{m}` since the chapter was last revised", "", "Commits (newest first):", ""]
        parts += [f"- {c.short} {c.subject}" for c in commits[:max_log]]
        if len(commits) > max_log:
            parts.append(f"- ... and {len(commits) - max_log} older commits")
        diff = module_diff(ctx, plan.base_commit, plan.module_files.get(m, []), limit)
        if diff:
            parts += ["", "Condensed diff:", "", "```diff", diff.rstrip(), "```"]
        parts.append("")
    parts += ["## Available images (relative to this chapter)", ""]
    chapter_dir = ctx.chapter_file(plan.chapter).parent
    for img in available_images(ctx):
        rel = posix_relpath(img, chapter_dir)
        note = " (placeholder: generic preview render, not the real screen; prefer not to describe it)" if img.parent == ctx.img_dir and img.stem in placeholders_set else ""
        parts.append(f"- `{rel}`{note}")
    for sid in sorted(reg.shots):
        if not shot_file(ctx, sid).exists():
            parts.append(f"- `{image_rel(ctx, plan.chapter, sid)}` (registry screenshot `{sid}`, not rendered yet; you may reference it)")
    parts += ["", "## Current chapter text", "", "<current_chapter>", text.rstrip("\n"), "</current_chapter>", ""]
    parts += ["Return the full revised chapter in <revised_chapter> tags, or <unchanged/>."]
    return "\n".join(parts)


@dataclasses.dataclass
class ModelResult:
    text: str
    stop_reason: str | None
    usage: dict[str, Any]
    model: str | None = None


class ModelError(Exception):
    pass


def model_settings(ctx: Ctx) -> dict[str, Any]:
    model = os.environ.get("EZYX_DOCS_MODEL") or ctx.config["model"]
    fb_env = os.environ.get("EZYX_DOCS_FALLBACKS")
    fallbacks = (fb_env not in ("0", "false", "no")) if fb_env is not None else model in FALLBACK_MODELS
    return {
        "model": model,
        "effort": os.environ.get("EZYX_DOCS_EFFORT") or ctx.config.get("effort"),
        "max_tokens": int(os.environ.get("EZYX_DOCS_MAX_TOKENS") or ctx.config["max_tokens"]),
        "fallbacks": fallbacks,
    }


def call_claude(system: list[dict[str, Any]], user: str, settings: dict[str, Any]) -> ModelResult:
    """One Messages API request: the anthropic SDK if installed, else plain HTTPS via urllib."""
    try:
        import anthropic  # type: ignore
    except ImportError:
        anthropic = None  # type: ignore
    if anthropic is not None and os.environ.get("EZYX_DOCS_NO_SDK") != "1":
        return _call_sdk(anthropic, system, user, settings)
    return _call_urllib(system, user, settings)


def _request_kwargs(system: list[dict[str, Any]], user: str, settings: dict[str, Any]) -> dict[str, Any]:
    body: dict[str, Any] = {
        "model": settings["model"],
        "max_tokens": settings["max_tokens"],
        "system": system,
        "messages": [{"role": "user", "content": user}],
    }
    if settings.get("effort"):
        body["output_config"] = {"effort": settings["effort"]}
    return body


def _call_sdk(anthropic: Any, system: list[dict[str, Any]], user: str, settings: dict[str, Any]) -> ModelResult:
    client = anthropic.Anthropic(max_retries=4)
    kwargs = _request_kwargs(system, user, settings)
    try:
        if settings.get("fallbacks"):
            # Server-side refusal fallback: a declined request is retried on Anthropic's recommended model.
            stream_cm = client.beta.messages.stream(**kwargs, betas=[FALLBACK_BETA], extra_body={"fallbacks": "default"})
        else:
            stream_cm = client.messages.stream(**kwargs)
        with stream_cm as stream:
            msg = stream.get_final_message()
    except TypeError:
        # An SDK too old for these parameters: fall back to the plain HTTPS client.
        return _call_urllib(system, user, settings)
    except anthropic.APIStatusError as e:  # 4xx/5xx after the SDK's own retries
        raise ModelError(f"API error {e.status_code}: {getattr(e, 'message', e)}") from e
    except anthropic.APIConnectionError as e:
        raise ModelError(f"connection error: {e}") from e
    text = "".join(getattr(b, "text", "") for b in msg.content if getattr(b, "type", "") == "text")
    usage = msg.usage.model_dump() if hasattr(msg.usage, "model_dump") else dict(vars(msg.usage))
    return ModelResult(text, msg.stop_reason, usage, getattr(msg, "model", None))


def _call_urllib(system: list[dict[str, Any]], user: str, settings: dict[str, Any]) -> ModelResult:
    key = os.environ.get("ANTHROPIC_API_KEY")
    token = os.environ.get("ANTHROPIC_AUTH_TOKEN")
    base = (os.environ.get("ANTHROPIC_BASE_URL") or "https://api.anthropic.com").rstrip("/")
    body = _request_kwargs(system, user, settings)
    headers = {"content-type": "application/json", "anthropic-version": API_VERSION}
    betas = []
    if key:
        headers["x-api-key"] = key
    elif token:
        headers["authorization"] = f"Bearer {token}"
    if settings.get("fallbacks"):
        body["fallbacks"] = "default"
        betas.append(FALLBACK_BETA)
    if betas:
        headers["anthropic-beta"] = ",".join(betas)
    data = json.dumps(body).encode("utf-8")
    last_err = ""
    for attempt in range(5):
        req = urllib.request.Request(f"{base}/v1/messages", data=data, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=900) as resp:
                msg = json.loads(resp.read().decode("utf-8"))
            text = "".join(b.get("text", "") for b in msg.get("content", []) if b.get("type") == "text")
            return ModelResult(text, msg.get("stop_reason"), msg.get("usage", {}), msg.get("model"))
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")[:500]
            last_err = f"API error {e.code}: {detail}"
            if e.code in (408, 409, 429) or e.code >= 500:
                wait = float(e.headers.get("retry-after") or 0) or min(60.0, 2.0 * 2**attempt)
                time.sleep(wait)
                continue
            raise ModelError(last_err) from e
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            last_err = f"connection error: {e}"
            time.sleep(min(60.0, 2.0 * 2**attempt))
    raise ModelError(last_err or "request failed")


def extract_revision(response: str) -> str | None:
    """The chapter inside <revised_chapter> tags; None for <unchanged/>. Raises ValueError if neither."""
    if re.fullmatch(r"\s*<unchanged\s*/>\s*", response):
        return None
    m = re.search(r"<revised_chapter>\s*\n?(.*?)\n?\s*</revised_chapter>", response, re.S)
    if not m:
        if "<unchanged" in response and "<revised_chapter>" not in response:
            return None
        raise ValueError("response has no <revised_chapter> block")
    body = m.group(1)
    fence = re.fullmatch(r"\s*(```+|~~~+)(?:markdown|md)?\s*\n(.*)\n\s*\1\s*", body, re.S)
    if fence:
        body = fence.group(2)
    return normalize_text(body)


def validate_revision(
    original: str,
    revised: str,
    *,
    chapter_file: Path,
    src_dir: Path,
    required_ids: list[str],
    removed_ids: list[str],
    pending_images: Iterable[Path] = (),
) -> tuple[list[str], list[str]]:
    """Check an LLM-revised chapter before it replaces the original. Returns (errors, warnings).

    ``pending_images`` are registry screenshots that are allowed although not rendered yet.
    """
    pending = {p.resolve() for p in pending_images}
    errors: list[str] = []
    warnings: list[str] = []
    blocks, perrs = parse_blocks(revised)
    errors += [f"line {ln}: {e}" for ln, e in perrs]
    ids = [b.id for b in blocks]
    orig_blocks, _ = parse_blocks(original)
    orig_ids = {b.id for b in orig_blocks}
    for rid in required_ids:
        if rid not in ids:
            errors.append(f"marker block for feature {rid!r} is missing")
    for bid in ids:
        if bid not in required_ids:
            if bid in removed_ids or bid in orig_ids:
                warnings.append(f"block {bid!r} for a removed/foreign feature was kept")
            else:
                errors.append(f"unknown feature block {bid!r} was introduced")
    for line, url in image_refs(revised):
        if is_external(url):
            errors.append(f"line {line}: external image {url!r}")
            continue
        target = resolve_ref(chapter_file, url)
        try:
            target.relative_to(src_dir.resolve())
        except ValueError:
            errors.append(f"line {line}: image {url!r} is outside the manual")
            continue
        if not target.exists() and target not in pending:
            errors.append(f"line {line}: image {url!r} does not exist")
    for line, url in local_links(revised):
        if not resolve_ref(chapter_file, url).exists():
            errors.append(f"line {line}: link to missing file {url!r}")
    if first_h1(original) and not first_h1(revised):
        errors.append("the chapter lost its `# ` title")
    if re.search(r"</?(revised_chapter|current_chapter)>", revised):
        errors.append("response contains prompt tags")
    o, r = len(original.strip()), len(revised.strip())
    if o > 600 and r < 0.4 * o:
        (warnings if removed_ids else errors).append(f"revised chapter is much shorter than the original ({r} vs {o} characters)")
    orig_out = {t for lvl, t in headings(outside_blocks(original, orig_blocks)) if lvl > 1}
    new_heads = {t for _, t in headings(revised)}
    for h in sorted(orig_out - new_heads):
        warnings.append(f"hand-written section {h!r} was removed or renamed")
    return errors, warnings


def api_key_present() -> bool:
    return bool(os.environ.get("ANTHROPIC_API_KEY") or os.environ.get("ANTHROPIC_AUTH_TOKEN"))


def print_plan(ctx: Ctx, plans: list[ChapterPlan], limit: int) -> None:
    if not plans:
        ctx.log.info("revise: the manual is up to date; nothing to revise")
        return
    ctx.log.info(f"revise: {len(plans)} chapter(s) need revision" + (f" (this run handles the first {limit})" if len(plans) > limit else ""))
    for p in plans:
        ctx.log.info(f"  - {p.chapter}")
        for r in p.reasons:
            ctx.log.info(f"      {r}")


def revise(
    ctx: Ctx,
    *,
    chapters: list[str] | None = None,
    call: Callable[[list[dict[str, Any]], str, dict[str, Any]], ModelResult] | None = None,
    summary_out: Path | None = None,
) -> int:
    reg, errors = load_registry(ctx)
    for e in errors:
        ctx.log.error(e, ctx.rel(ctx.registry_path))
    if reg is None or errors:
        return 1
    state = load_state(ctx)
    plans = all_plans = plan_revisions(ctx, reg, state)
    if chapters:
        plans = [p for p in plans if p.chapter in chapters]
    limit = int(ctx.config["max_chapters_per_run"])
    print_plan(ctx, plans, limit)
    report: list[str] = []
    if not plans:
        _write_summary(summary_out, ["The manual is up to date with the feature registry and source history."])
        return 0
    if ctx.dry_run:
        ctx.log.info("revise: --dry-run, no API calls made")
        return 0
    if call is None and not api_key_present():
        ctx.log.info("revise: ANTHROPIC_API_KEY is not set; skipping the LLM step (the plan above is what would be revised)")
        _write_summary(summary_out, ["LLM revision skipped (no `ANTHROPIC_API_KEY`). Chapters that need revision:"] + [f"- `{p.chapter}`: {'; '.join(p.reasons)}" for p in plans])
        return 0
    call = call or call_claude
    settings = model_settings(ctx)
    system = build_system_blocks(ctx, reg)
    head = git_head(ctx)
    succeeded: list[ChapterPlan] = []
    failed: list[ChapterPlan] = []
    api_failures = 0
    for plan in plans[:limit]:
        path = ctx.chapter_file(plan.chapter)
        original = read_text(path) or ""
        user = build_user_prompt(ctx, reg, plan, state)
        ctx.log.info(f"revise: {plan.chapter} ({len(user)} chars) -> {settings['model']}")
        try:
            res = call(system, user, settings)
        except ModelError as e:
            ctx.log.warning(f"{plan.chapter}: model call failed, keeping the old chapter: {e}", ctx.rel(path))
            failed.append(plan)
            api_failures += 1
            report.append(f"- `{plan.chapter}`: not revised (API error)")
            continue
        usage = res.usage or {}
        ctx.log.info(
            f"  stop={res.stop_reason} in={usage.get('input_tokens')} cache_read={usage.get('cache_read_input_tokens')} "
            f"cache_write={usage.get('cache_creation_input_tokens')} out={usage.get('output_tokens')}"
        )
        if res.stop_reason not in ("end_turn", "stop_sequence"):
            ctx.log.warning(f"{plan.chapter}: model stopped with {res.stop_reason!r}; keeping the old chapter", ctx.rel(path))
            failed.append(plan)
            report.append(f"- `{plan.chapter}`: not revised (stop reason `{res.stop_reason}`)")
            continue
        try:
            revised = extract_revision(res.text)
        except ValueError as e:
            ctx.log.warning(f"{plan.chapter}: {e}; keeping the old chapter", ctx.rel(path))
            failed.append(plan)
            report.append(f"- `{plan.chapter}`: not revised (unparseable response)")
            continue
        if revised is None or revised == normalize_text(original):
            ctx.log.info("  chapter unchanged")
            succeeded.append(plan)
            report.append(f"- `{plan.chapter}`: reviewed, no changes needed")
            continue
        errs, warns = validate_revision(
            original,
            revised,
            chapter_file=path,
            src_dir=ctx.src_dir,
            required_ids=plan.feature_ids,
            removed_ids=plan.removed_ids,
            pending_images=[shot_file(ctx, sid) for sid in reg.shots],
        )
        for w in warns:
            ctx.log.warning(f"{plan.chapter}: {w}", ctx.rel(path))
        if errs:
            for e in errs:
                ctx.log.warning(f"{plan.chapter}: rejected revision: {e}", ctx.rel(path))
            failed.append(plan)
            report.append(f"- `{plan.chapter}`: revision rejected by validation ({errs[0]})")
            continue
        write_if_changed(ctx, path, revised, "revised")
        succeeded.append(plan)
        report.append(f"- `{plan.chapter}`: revised ({'; '.join(plan.reasons)})")
    deferred = plans[limit:]
    for p in deferred:
        report.append(f"- `{p.chapter}`: deferred to the next run (max_chapters_per_run={limit})")
    if succeeded:
        freeze_changelog(ctx, state, reg, head)
        pending = [p for p in all_plans if p not in succeeded]
        save_state(ctx, next_state(reg, state, succeeded, pending, head))
    _write_summary(summary_out, ["Chapters handled by the LLM revision step:"] + report)
    ctx.log.info(f"revise: {len(succeeded)} ok, {len(failed)} kept unchanged after errors, {len(deferred)} deferred")
    attempted = len(plans[:limit])
    if attempted and api_failures == attempted:
        ctx.log.error("every model call failed; check ANTHROPIC_API_KEY / EZYX_DOCS_MODEL and network access")
        return 3
    return 0


def next_state(reg: Registry, state: dict[str, Any] | None, ok: list[ChapterPlan], pending: list[ChapterPlan], head: str | None) -> dict[str, Any]:
    st = json.loads(json.dumps(state)) if state else {"features": {}, "chapters": {}}
    st["version"] = 1
    old_commit = st.get("commit")
    now = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()
    pending_chapters = {p.chapter for p in pending}
    for plan in ok:
        st["chapters"][plan.chapter] = {"commit": head, "revised_at": now}
        for fid in plan.feature_ids:
            f = reg.feature_by_id[fid]
            st["features"][fid] = {"hash": reg.feature_hash(f), "chapter": plan.chapter, "entry": f}
        for fid in plan.removed_ids:
            st["features"].pop(fid, None)
    for plan in pending:
        st["chapters"].setdefault(plan.chapter, {"commit": old_commit})
    # Chapters that needed nothing are current as of this run, too.
    planned = {p.chapter for p in ok} | pending_chapters
    for ch in reg.chapters():
        if ch not in planned:
            for f in reg.features_in_chapter(ch):
                st["features"].setdefault(f["id"], {"hash": reg.feature_hash(f), "chapter": ch, "entry": f})
            st["chapters"].setdefault(ch, {"commit": old_commit or head})
    st["commit"] = head
    st["app_version"] = reg.app_version
    st["registry_hash"] = reg.registry_hash()
    st["revised_at"] = now
    return st


def _write_summary(path: Path | None, lines: list[str]) -> None:
    if path is None:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n\n")


