@dataclasses.dataclass
class Ctx:
    root: Path
    config: dict[str, Any]
    dry_run: bool = False
    log: Log = dataclasses.field(default_factory=Log)

    def path(self, key: str) -> Path:
        return (self.root / self.config[key]).resolve()

    @property
    def src_dir(self) -> Path:
        return self.path("src_dir")

    @property
    def img_dir(self) -> Path:
        return self.path("img_dir")

    @property
    def registry_path(self) -> Path:
        return self.path("registry")

    @property
    def state_path(self) -> Path:
        return self.path("state_file")

    @property
    def summary_path(self) -> Path:
        return self.src_dir / "SUMMARY.md"

    def rel(self, p: Path) -> str:
        """Repository-relative posix path for messages."""
        try:
            return p.resolve().relative_to(self.root.resolve()).as_posix()
        except ValueError:
            return p.as_posix()

    def chapter_file(self, chapter: str) -> Path:
        return self.src_dir / chapter


def load_config(root: Path, config_path: Path | None = None) -> dict[str, Any]:
    cfg = json.loads(json.dumps(DEFAULT_CONFIG))
    path = config_path or (root / "tools" / "docs" / "config.json")
    if path.exists():
        user = json.loads(path.read_text(encoding="utf-8"))
        for k, v in user.items():
            if k.startswith("_"):
                continue
            if isinstance(v, dict) and isinstance(cfg.get(k), dict):
                cfg[k].update(v)
            else:
                cfg[k] = v
    return cfg


def make_ctx(root: Path, config_path: Path | None = None, dry_run: bool = False, quiet: bool = False) -> Ctx:
    return Ctx(root=root.resolve(), config=load_config(root, config_path), dry_run=dry_run, log=Log(quiet=quiet))


