#!/usr/bin/env bash
# Build libezyx_mobile.a for iPad (device) and the Apple-silicon simulator, and write
# Rust.xcconfig for the Xcode project. Run from anywhere on a Mac with Xcode and rustup:
#   mobile/ios/build-rust.sh            # release
#   PROFILE=debug mobile/ios/build-rust.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
profile="${PROFILE:-release}"
flag=$([ "$profile" = release ] && echo --release || true)
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-16.0}"
export IPHONESIMULATOR_DEPLOYMENT_TARGET="${IPHONESIMULATOR_DEPLOYMENT_TARGET:-$IPHONEOS_DEPLOYMENT_TARGET}"

rustup target add aarch64-apple-ios aarch64-apple-ios-sim >/dev/null
libs=""
for target in aarch64-apple-ios aarch64-apple-ios-sim; do
  # --print native-static-libs lists the frameworks/libraries the static library needs; rustc
  # only prints it when it links, so make sure the crate is rebuilt.
  touch "$root/crates/ezyx-mobile/src/lib.rs"
  # No colours: with CARGO_TERM_COLOR=always (CI) the note ends in an ANSI reset that would end up
  # in the linker flags ("library 'm\e[0m' not found").
  out=$(cd "$root" && cargo rustc $flag --color never -p ezyx-mobile --target "$target" --crate-type staticlib -- --print native-static-libs 2>&1 | tee /dev/stderr)
  libs=$(printf '%s\n' "$out" | sed -n 's/.*native-static-libs: //p' | tail -1 | sed "s/$(printf '\033')\[[0-9;]*m//g")
  # -lezyx_mobile must find the static library, not a dylib from an earlier build.
  rm -f "$root/target/$target/$profile/libezyx_mobile.dylib"
done
if [ -z "$libs" ]; then
  libs="-framework UIKit -framework Foundation -framework CoreFoundation -framework CoreGraphics -framework QuartzCore -framework Metal -framework Security -lobjc -liconv -lc -lm"
  echo "warning: rustc printed no native-static-libs; using the default framework list" >&2
fi

cat > "$here/Rust.xcconfig" <<XC
// Generated by build-rust.sh — do not edit.
LIBRARY_SEARCH_PATHS[sdk=iphoneos*] = \$(inherited) $root/target/aarch64-apple-ios/$profile
LIBRARY_SEARCH_PATHS[sdk=iphonesimulator*] = \$(inherited) $root/target/aarch64-apple-ios-sim/$profile
RUST_LDFLAGS = $libs
XC
echo "wrote $here/Rust.xcconfig (RUST_LDFLAGS = $libs)"
