//! Output step helpers: a job summary (time, bits in order, tool changes, warnings) and a
//! printable HTML job sheet for the workshop wall.

use crate::ops::OpResult;
use crate::pipeline::Conflict;
use crate::Project;
use ezyx_tooldb::ToolLibrary;

#[derive(Debug, Clone, PartialEq)]
pub struct JobStep {
    pub op_name: String,
    pub feature: Option<String>,
    pub tool_id: String,
    pub tool_name: String,
    pub pass: ezyx_tooldb::Operation,
    pub depth: f64,
    pub rpm: f64,
    pub feed: f64,
    pub seconds: f64,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct JobSummary {
    pub steps: Vec<JobStep>,
    pub total_seconds: f64,
    /// Distinct tools in the order they're needed.
    pub tools_in_order: Vec<String>,
    pub tool_changes: usize,
    pub errors: Vec<String>,
}

pub fn summarize(p: &Project, lib: &ToolLibrary, results: &[OpResult]) -> JobSummary {
    let mut s = JobSummary::default();
    let mut last_tool: Option<String> = None;
    for op in p.operations.iter().filter(|o| o.enabled) {
        let Some(r) = results.iter().find(|r| r.op_id == op.id) else { continue };
        if let Some(e) = &r.error {
            s.errors.push(format!("{}: {e}", op.name));
        }
        for tp in &r.toolpaths {
            let st = tp.stats(p.machine.limits.max_feed);
            s.total_seconds += st.est_seconds;
            if last_tool.as_deref() != Some(tp.tool.id.as_str()) {
                if last_tool.is_some() {
                    s.tool_changes += 1;
                }
                last_tool = Some(tp.tool.id.clone());
                if !s.tools_in_order.contains(&tp.tool.name) {
                    s.tools_in_order.push(tp.tool.name.clone());
                }
            }
            s.steps.push(JobStep {
                op_name: tp.name.clone(),
                feature: op.feature_id.and_then(|f| p.features.iter().find(|x| x.id == f)).map(|f| f.name.clone()),
                tool_id: tp.tool.id.clone(),
                tool_name: lib.get(&tp.tool.id).map(|t| t.name.clone()).unwrap_or_else(|| tp.tool.name.clone()),
                pass: crate::pipeline::toolpath_pass(op, tp),
                depth: op.cut_depth,
                rpm: tp.cutting.rpm,
                feed: tp.cutting.feed,
                seconds: st.est_seconds,
            });
        }
    }
    s
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

/// Self-contained HTML job sheet.
pub fn html(p: &Project, s: &JobSummary, conflicts: &[Conflict]) -> String {
    let j = &p.job;
    let u = j.display_units;
    let mat = ezyx_materials::find(&j.material).map(|m| m.name).unwrap_or_else(|| j.material.clone());
    let mut rows = String::new();
    for (i, st) in s.steps.iter().enumerate() {
        rows += &format!(
            "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{:?}</td><td>{}</td><td>{:.0}</td><td>{:.0}</td><td>{:.1}</td></tr>\n",
            i + 1,
            esc(&st.op_name),
            esc(st.feature.as_deref().unwrap_or("—")),
            esc(&st.tool_name),
            st.pass,
            u.fmt(st.depth),
            st.rpm,
            st.feed,
            st.seconds / 60.0
        );
    }
    let mut warn = String::new();
    for c in conflicts {
        warn += &format!("<li class=\"{:?}\">{}</li>", c.severity, esc(&c.message));
    }
    for e in &s.errors {
        warn += &format!("<li class=\"Error\">{}</li>", esc(e));
    }
    format!(
        r#"<!doctype html><html><head><meta charset="utf-8"><title>Job sheet — {name}</title>
<style>body{{font-family:system-ui,sans-serif;margin:2em;color:#222}}h1{{color:#e87828}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #ccc;padding:4px 8px;text-align:left}}th{{background:#f4ede3}}.Error{{color:#c33}}.Warning{{color:#b80}}.Info{{color:#567}}</style></head>
<body><h1>Job sheet — {name}</h1>
<p><b>Stock</b> {w} × {h} × {t} ({shape}) · <b>Material</b> {mat} · <b>XY zero</b> {datum:?} · <b>Z zero</b> {zz:?}</p>
<p><b>Machine</b> {machine} · <b>Post</b> {post} · <b>Estimated time</b> {mins:.0} min · <b>Tool changes</b> {tc}</p>
<p><b>Bits in order:</b> {tools}</p>
<table><tr><th>#</th><th>Toolpath</th><th>Feature</th><th>Bit</th><th>Pass</th><th>Depth</th><th>RPM</th><th>Feed mm/min</th><th>min</th></tr>
{rows}</table>
<h2>Checks</h2><ul>{warn}</ul>
<p><small>Generated by EZ-YX-craft {ver}. Verify feeds with a test cut.</small></p></body></html>"#,
        name = esc(&p.name),
        w = u.fmt(j.width),
        h = u.fmt(j.height),
        t = u.fmt(j.thickness),
        shape = p.stock_shape.label(),
        datum = j.xy_datum,
        zz = j.z_zero,
        machine = esc(&p.machine.name),
        post = esc(&p.post_id),
        mins = s.total_seconds / 60.0,
        tc = s.tool_changes,
        tools = esc(&s.tools_in_order.join(" → ")),
        warn = if warn.is_empty() { "<li>No problems found.</li>".to_string() } else { warn },
        ver = env!("CARGO_PKG_VERSION"),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pipeline::{default_library, feature_from_vectors, CutStrategy};
    use crate::VectorSource;
    use ezyx_core::{path::shapes::rectangle, DVec2};

    #[test]
    fn summary_counts_tool_changes() {
        let mut p = Project::default();
        let a = p.add_vector("pocket", rectangle(DVec2::new(50.0, 50.0), 60.0, 40.0, 0.0), VectorSource::Drawn);
        let b = p.add_vector("outline", rectangle(DVec2::new(10.0, 10.0), 250.0, 160.0, 0.0), VectorSource::Drawn);
        feature_from_vectors(&mut p, default_library(), &[a], CutStrategy::Pocket, Some(3.0), None).unwrap();
        feature_from_vectors(&mut p, default_library(), &[b], CutStrategy::CutOut, None, None).unwrap();
        let res = crate::ops::compute_all(&p, default_library());
        let s = summarize(&p, default_library(), &res);
        assert_eq!(s.steps.len(), 4);
        // 1/4" rough pocket → 1/8" finish pocket → 1/4" rough cut-out → 1/4" finish cut-out.
        assert_eq!(s.tool_changes, 2, "{:?}", s.steps.iter().map(|x| &x.tool_id).collect::<Vec<_>>());
        assert!(s.total_seconds > 0.0);
        let h = html(&p, &s, &[]);
        assert!(h.contains("Job sheet") && h.contains("No problems found"));
    }
}
